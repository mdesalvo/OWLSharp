using System.Collections.Generic;
using System;
using RDFSharp.Model;
using RDFSharp.Query;

namespace OWLSharp.Ontology
{
    /// <summary>
    /// SWRLCosBuiltIn implements the standard http://www.w3.org/2003/11/swrlb#cos built-in
    /// </summary>
    internal static class SWRLCosBuiltIn
    {
        #region Methods
        /// <summary>
        /// Computes the cosine of the second argument
        /// </summary>
        /// <exception cref="ArgumentException"></exception>
        internal static RDFLiteral EvaluateOnAntecedent(RDFTableRow antecedentResultsRow, List<SWRLArgument> builtInArguments)
        {
            #region Guards
            if (builtInArguments?.Count != 2)
                throw new ArgumentException("it requires exactly 2 arguments");
            #endregion

            //Only numbers take part in the computation: an unbound or non-numeric operand leaves the result undefined
            if (!SWRLHelper.TryGetNumericOperands(antecedentResultsRow, builtInArguments, out SWRLNumericFamily _, out decimal[] _, out double[] approximateOperands))
                return null;

            //A trigonometric value is irrational in general, so it is always computed in double precision
            return SWRLHelper.ToNumericLiteral(Math.Cos(approximateOperands[0]));
        }
        #endregion
    }
}
